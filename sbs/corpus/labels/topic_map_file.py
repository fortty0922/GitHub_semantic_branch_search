import json
from pathlib import Path

HEADER = """# Generated by `python -m sbs corpus discover-topics`; do not edit by hand.
# Seeds are in domains.toml and thresholds in experiment.toml [corpus.topics].
# `topics` are used for labels; `query_topics` (early discovery rounds only) for crawl queries.
"""


def toml_list(key: str, items: list[str]) -> list[str]:
    return [f"{key} = [", *(f"    {json.dumps(t)}," for t in items), "]"]


def write(path: str | Path, topics: dict[str, list[str]], query_topics: dict[str, list[str]] | None = None) -> None:
    lines = [HEADER]
    for domain, tags in topics.items():
        lines.append(f"[{domain}]")
        lines.extend(toml_list("topics", tags))
        if query_topics is not None:
            lines.extend(toml_list("query_topics", query_topics.get(domain, [])))
        lines.append("")
    Path(path).write_text("\n".join(lines), encoding="utf-8")
