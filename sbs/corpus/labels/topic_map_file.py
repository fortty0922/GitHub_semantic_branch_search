import json
from pathlib import Path

HEADER = """# Generated by `python -m sbs corpus discover-topics`; do not edit by hand.
# Seeds are in domains.toml and thresholds in experiment.toml [corpus.topics].
"""


def write(path: str | Path, topics: dict[str, list[str]]) -> None:
    lines = [HEADER]
    for domain, tags in topics.items():
        lines.append(f"[{domain}]")
        lines.append("topics = [")
        lines.extend(f"    {json.dumps(t)}," for t in tags)
        lines.append("]")
        lines.append("")
    Path(path).write_text("\n".join(lines), encoding="utf-8")
